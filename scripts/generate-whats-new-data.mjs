#!/usr/bin/env node
//
// Regenerate constants/whats-new-data.generated.js from STORE_LISTING.md.
//
// Motivation: The extension shows an in-popup "What's new" panel after an
// update. Rather than shipping STORE_LISTING.md and exposing it via
// web_accessible_resources (which would leak marketing/permissions prose and
// require a manifest change), we compile the user-voiced "What's new in X.Y.Z:"
// blocks into a small bundled ES module at build time. That module is imported
// directly by the popup/sidebar UI.
//
// Source of truth: the "What's new in X.Y.Z:" blocks in STORE_LISTING.md.
// These are already human-polished, flat, store-voice bullets — no markdown
// bold/link/backtick normalization is needed (unlike CHANGELOG.md).
//
// Behavior:
//   - Parses every "What's new in X.Y.Z:" block from STORE_LISTING.md.
//   - Emits constants/whats-new-data.generated.js with WHATS_NEW (a version →
//     {title, bullets[]} map) and WHATS_NEW_VERSIONS (newest-first version list).
//   - --check mode: regenerate in-memory and compare to the committed file;
//     exit 1 on drift (mirrors store:listing:check).
//
// Usage:
//   node scripts/generate-whats-new-data.mjs            # write the file
//   node scripts/generate-whats-new-data.mjs --check    # verify no drift
//   node scripts/generate-whats-new-data.mjs --stdout   # print, don't write

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const LISTING_PATH = path.join(ROOT_DIR, 'STORE_LISTING.md');
const OUTPUT_PATH = path.join(ROOT_DIR, 'constants', 'whats-new-data.generated.js');

const BLOCK_HEADER_RE = /^What's new in (\d+\.\d+\.\d+):$/;

// -----------------------------------------------------------------------------
// Parsing
// -----------------------------------------------------------------------------

/**
 * Parse all "What's new in X.Y.Z:" blocks from STORE_LISTING.md text.
 * A block runs from its header line until the next block header, a blank line
 * followed by a non-bullet line, or EOF. Returns an array (in document order)
 * of { version, title, bullets: string[] }.
 */
export function parseWhatsNewBlocks(text) {
  const lines = text.split('\n');
  const blocks = [];
  let current = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const m = line.match(BLOCK_HEADER_RE);
    if (m) {
      if (current) blocks.push(current);
      current = { version: m[1], title: line.replace(/:$/, ''), bullets: [] };
      continue;
    }
    if (!current) continue;

    if (line.startsWith('- ')) {
      current.bullets.push(line.slice(2).trim());
      continue;
    }
    // Continuation line for the previous bullet (indented, non-empty).
    if (/^\s+\S/.test(line) && current.bullets.length > 0) {
      current.bullets[current.bullets.length - 1] += ' ' + line.trim();
      continue;
    }
    // A blank line or any other non-bullet content ends the current block.
    if (line.trim() === '' || !line.startsWith('- ')) {
      blocks.push(current);
      current = null;
    }
  }
  if (current) blocks.push(current);

  // Drop any accidental empty blocks (header with no bullets).
  return blocks.filter((b) => b.bullets.length > 0);
}

/**
 * Numeric-descending comparison for "major.minor.patch" strings.
 */
export function compareVersionsDesc(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const d = (pb[i] || 0) - (pa[i] || 0);
    if (d !== 0) return d;
  }
  return 0;
}

/**
 * Build the generated ES module source from parsed blocks.
 */
export function buildModuleSource(blocks) {
  const sorted = [...blocks].sort((x, y) => compareVersionsDesc(x.version, y.version));

  const entries = sorted
    .map((b) => {
      const bullets = b.bullets.map((s) => `      ${JSON.stringify(s)}`).join(',\n');
      return `  ${JSON.stringify(b.version)}: {\n    title: ${JSON.stringify(b.title)},\n    bullets: [\n${bullets}\n    ]\n  }`;
    })
    .join(',\n');

  const versions = sorted.map((b) => JSON.stringify(b.version)).join(', ');

  return `// AUTO-GENERATED by scripts/generate-whats-new-data.mjs — DO NOT EDIT BY HAND.
// Source: STORE_LISTING.md ("What's new in X.Y.Z:" blocks).
// Regenerate with: npm run whatsnew:data

export const WHATS_NEW = {
${entries}
};

// Newest-first list of versions that have release notes.
export const WHATS_NEW_VERSIONS = [${versions}];
`;
}

// -----------------------------------------------------------------------------
// Main
// -----------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  const mode = args.includes('--check')
    ? 'check'
    : args.includes('--stdout')
      ? 'stdout'
      : 'write';

  if (!fs.existsSync(LISTING_PATH)) {
    console.error(`❌ STORE_LISTING not found: ${LISTING_PATH}`);
    process.exit(1);
  }

  const listingText = fs.readFileSync(LISTING_PATH, 'utf8');
  const blocks = parseWhatsNewBlocks(listingText);
  if (blocks.length === 0) {
    console.error('❌ No "What\'s new in X.Y.Z:" blocks found in STORE_LISTING.md');
    process.exit(1);
  }

  const nextSource = buildModuleSource(blocks);

  if (mode === 'stdout') {
    process.stdout.write(nextSource);
    return;
  }

  if (mode === 'check') {
    if (!fs.existsSync(OUTPUT_PATH)) {
      console.error(`❌ ${path.relative(ROOT_DIR, OUTPUT_PATH)} is missing. Run: npm run whatsnew:data`);
      process.exit(1);
    }
    const current = fs.readFileSync(OUTPUT_PATH, 'utf8');
    if (current !== nextSource) {
      console.error(
        `❌ ${path.relative(ROOT_DIR, OUTPUT_PATH)} is out of date. Run: npm run whatsnew:data`,
      );
      process.exit(1);
    }
    console.log(`✅ ${path.relative(ROOT_DIR, OUTPUT_PATH)} is up to date (${blocks.length} versions).`);
    return;
  }

  fs.writeFileSync(OUTPUT_PATH, nextSource);
  console.log(
    `✅ Wrote ${path.relative(ROOT_DIR, OUTPUT_PATH)} (${blocks.length} versions, newest ${blocks.map((b) => b.version).sort(compareVersionsDesc)[0]}).`,
  );
}

// Run only when invoked directly (not when imported by tests).
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
